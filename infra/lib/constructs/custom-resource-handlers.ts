import { CfnResource, RemovalPolicy, Stack } from 'aws-cdk-lib';
import { Role, ServicePrincipal } from 'aws-cdk-lib/aws-iam';
import { CfnFunction } from 'aws-cdk-lib/aws-lambda';
import { LogGroup, RetentionDays } from 'aws-cdk-lib/aws-logs';
import {
  AwsCustomResource,
  type AwsCustomResourceProps,
} from 'aws-cdk-lib/custom-resources';
import { NagSuppressions } from 'cdk-nag';
import { Construct, type IConstruct } from 'constructs';

// Every AwsCustomResource in a stack shares one handler, created with the
// props of the first. Changing its name changes its ARN, and CloudFormation
// will not update the ServiceToken of an existing custom resource, so naming
// a live handler means giving its custom resources new construct ids.

export type AwsCustomResourceHandlerProps = Pick<
  AwsCustomResourceProps,
  'functionName' | 'role' | 'logGroup'
>;

/**
 * Name, role and log group for the stack's AwsCustomResource handler; pass
 * the result to every AwsCustomResource in the stack.
 */
export function awsCustomResourceHandler(
  scope: IConstruct,
  name: string,
): AwsCustomResourceHandlerProps {
  const stack = Stack.of(scope);
  const id = 'AwsCustomResourceHandler';
  const existing = stack.node.tryFindChild(id);
  if (existing instanceof HandlerResources) {
    if (existing.name !== name) {
      throw new Error(
        `${stack.stackName} AwsCustomResource handler is already named ${existing.name}`,
      );
    }
    return existing.props;
  }
  return new HandlerResources(stack, id, name).props;
}

class HandlerResources extends Construct {
  readonly props: AwsCustomResourceHandlerProps;

  constructor(
    scope: Construct,
    id: string,
    readonly name: string,
  ) {
    super(scope, id);
    const logGroup = new LogGroup(this, 'Logs', {
      logGroupName: `/aws/lambda/${name}`,
      retention: RetentionDays.TWO_WEEKS,
      removalPolicy: RemovalPolicy.DESTROY,
    });
    const role = new Role(this, 'Role', {
      roleName: name,
      description: `Runs the ${name} Lambda.`,
      assumedBy: new ServicePrincipal('lambda.amazonaws.com'),
    });
    logGroup.grantWrite(role);
    NagSuppressions.addResourceSuppressions(
      role,
      [
        {
          id: 'AwsSolutions-IAM5',
          reason: 'Log stream names are generated by Lambda.',
          appliesTo: [
            {
              regex:
                '/^Resource::<AwsCustomResourceHandlerLogs[A-F0-9]+\\.Arn>:\\*$/',
            },
          ],
        },
      ],
      true,
    );
    this.props = { functionName: name, role, logGroup };
  }
}

/** Labels the stack's AwsCustomResource singleton handler in the Lambda console. */
export function describeAwsCustomResourceHandler(
  scope: IConstruct,
  purpose: string,
): void {
  const stack = Stack.of(scope);
  const id = `AWS${AwsCustomResource.PROVIDER_FUNCTION_UUID.replaceAll('-', '')}`;
  const fn = stack.node.tryFindChild(id)?.node.defaultChild;
  if (!(fn instanceof CfnFunction)) {
    throw new Error(`${stack.stackName} has no AwsCustomResource handler`);
  }
  fn.description = handlerDescription(stack, 'AwsCustomResource', purpose);
}

/** Labels the handler behind the OpenIdConnectProvider L2 in the Lambda console. */
export function describeOpenIdConnectProviderHandler(scope: IConstruct): void {
  const stack = Stack.of(scope);
  const handler = stack.node
    .tryFindChild('Custom::AWSCDKOpenIdConnectProviderCustomResourceProvider')
    ?.node.tryFindChild('Handler');
  if (!(handler instanceof CfnResource)) {
    throw new Error(`${stack.stackName} has no OpenIdConnectProvider handler`);
  }
  handler.addPropertyOverride(
    'Description',
    handlerDescription(
      stack,
      'OpenIdConnectProvider',
      'creates and updates the GitHub Actions OIDC identity provider',
    ),
  );
}

function handlerDescription(
  stack: Stack,
  construct: string,
  purpose: string,
): string {
  const text = `${stack.stackName} CDK ${construct} handler: ${purpose}.`;
  if (text.length > 256) {
    throw new Error(`Lambda description over 256 characters: ${text}`);
  }
  return text;
}
