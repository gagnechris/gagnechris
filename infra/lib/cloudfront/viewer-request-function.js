/**
 * Every page URL that has no object goes to /404.html here, before S3:
 * CloudFront skips viewer-response functions when the origin returns 4xx, so
 * an S3 miss can't be turned into the HTML 404 later. There are no
 * distribution-wide error pages so /api and /assets keep their real 403/404.
 *
 * Post and project slugs are allowlisted in the KeyValueStore. Each namespace
 * fails open (any slug is served) until the publisher writes its sentinel, and
 * on any KVS error, so live pages never 404.
 */
import cf from 'cloudfront';

var PUBLISHED_KEYS_OVERRIDE = null;

var OPTION_B_PAGES_OVERRIDE = null;

/* PUBLISH_SURFACE_BEGIN */
// Generated by services/publisher/scripts/generate-publish-surface.ts — do not edit by hand.
// Publisher targets contribute optionBPaths; Vite static pages are listed in
// STATIC_OPTION_B_PAGES (services/publisher/src/publish-targets/surface.ts).
var OPTION_B_PAGES = [
  '/blog',
  '/contact',
  '/dont-feed-the-bears',
  '/dont-feed-the-bears/camp',
  '/dont-feed-the-bears/wild',
  '/projects',
  '/resume',
];

// KVS keys (packages/shared/src/slug-kvs.ts) and the slug cap (MAX_SLUG_LENGTH).
var BLOG_SYNCED_KEY = '__synced__';
var PROJECT_KEY_PREFIX = 'projects/';
var PROJECTS_SYNCED_KEY = 'projects/__synced__';
var MAX_SLUG_LENGTH = 120;
/* PUBLISH_SURFACE_END */

/** S3 keys stay under the storage prefix. */
var PUBLIC_POSTS_PREFIX = '/posts';
var STORAGE_POSTS_PREFIX = '/blog';

var PROJECTS_PREFIX = '/projects';

var LEGACY_RESUME_PDF = '/Christopher M Gagne Resume 2026.pdf';

var ADMIN_ORIGIN = 'https://admin.gagnechris.com';
var NOTEBOOK_ORIGIN = 'https://notebook.gagnechris.com';

async function handler(event) {
  var request = event.request;
  var host = request.headers.host.value.toLowerCase();

  if (host.indexOf('www.') === 0) {
    var apex = host.substring(4);
    return {
      statusCode: 301,
      statusDescription: 'Moved Permanently',
      headers: {
        location: {
          value:
            'https://' +
            apex +
            request.uri +
            serializeQueryString(request.querystring),
        },
      },
    };
  }

  var uri = request.uri;
  var appRedirect = appHostRedirect(uri, request.querystring);
  if (appRedirect !== null) {
    return {
      statusCode: 301,
      statusDescription: 'Moved Permanently',
      headers: {
        location: { value: appRedirect },
        // Bounds how long browsers hold the redirect if it is ever rolled back.
        'cache-control': { value: 'max-age=86400' },
      },
    };
  }

  if (isLegacyResumePdfUri(uri)) {
    return {
      statusCode: 301,
      statusDescription: 'Moved Permanently',
      headers: {
        location: {
          value: '/resume.pdf' + serializeQueryString(request.querystring),
        },
      },
    };
  }

  var legacyPostsUri = swapPathPrefix(
    uri,
    STORAGE_POSTS_PREFIX,
    PUBLIC_POSTS_PREFIX,
  );
  if (legacyPostsUri !== null) {
    return {
      statusCode: 301,
      statusDescription: 'Moved Permanently',
      headers: {
        location: {
          value: legacyPostsUri + serializeQueryString(request.querystring),
        },
      },
    };
  }

  var storagePostsUri = swapPathPrefix(
    uri,
    PUBLIC_POSTS_PREFIX,
    STORAGE_POSTS_PREFIX,
  );
  if (storagePostsUri !== null) {
    uri = storagePostsUri;
    request.uri = uri;
  }

  if (
    uri === '/api' ||
    uri.indexOf('/api/') === 0 ||
    uri === '/media' ||
    uri.indexOf('/media/') === 0 ||
    uri === '/.well-known' ||
    uri.indexOf('/.well-known/') === 0
  ) {
    return request;
  }

  // The publisher's template, not a public URL.
  if (uri === '/_shell.html') {
    return {
      statusCode: 404,
      statusDescription: 'Not Found',
      headers: {
        'content-type': { value: 'text/plain; charset=utf-8' },
      },
      body: 'Not Found',
    };
  }

  if (uri === '/' || uri === '/index.html') {
    request.uri = '/index.html';
    return request;
  }

  var page = pagePath(uri);
  if (page === null) {
    return request;
  }

  var projectSlug = childSlug(page, PROJECTS_PREFIX);
  if (projectSlug !== null) {
    await routeIfPublished(
      request,
      page,
      isValidSlug(projectSlug) ? PROJECT_KEY_PREFIX + projectSlug : null,
      PROJECTS_SYNCED_KEY,
    );
    return request;
  }

  if (isOptionBPage(page)) {
    request.uri = page + '/index.html';
    return request;
  }

  var blogSlug = childSlug(page, STORAGE_POSTS_PREFIX);
  if (blogSlug !== null) {
    await routeIfPublished(
      request,
      page,
      isValidSlug(blogSlug) ? blogSlug : null,
      BLOG_SYNCED_KEY,
    );
    return request;
  }

  notFound(request);
  return request;
}

/**
 * The page a URI names without its trailing `/` or `/index.html`, or null
 * for a file that is not a page (`/assets/app.js`, `/rss.xml`). Every `.html`
 * URI counts as a page, so an unknown one is the HTML 404 too.
 */
function pagePath(uri) {
  var page = uri;
  if (page.endsWith('/index.html')) {
    page = page.substring(0, page.length - '/index.html'.length);
  } else if (page.endsWith('/')) {
    page = page.substring(0, page.length - 1);
  } else {
    var lastSegment = page.substring(page.lastIndexOf('/') + 1);
    if (lastSegment.indexOf('.') !== -1 && !lastSegment.endsWith('.html')) {
      return null;
    }
  }
  return page;
}

/** `<slug>` for `<prefix>/<slug>`, or null. */
function childSlug(page, prefix) {
  if (page.indexOf(prefix + '/') !== 0) {
    return null;
  }
  var rest = page.substring(prefix.length + 1);
  if (!rest || rest.indexOf('/') !== -1) {
    return null;
  }
  return rest;
}

/** `key` null means the slug can't be published; it 404s without a KVS read. */
async function routeIfPublished(request, page, key, syncedKey) {
  if (key !== null && (await isPublishedKey(key, syncedKey))) {
    request.uri = page + '/index.html';
  } else {
    notFound(request);
  }
}

function notFound(request) {
  request.uri = '/404.html';
  // CloudFront would answer a validator left over from the page that used to
  // be here with a bodiless 304 for 404.html.
  delete request.headers['if-none-match'];
  delete request.headers['if-modified-since'];
}

function swapPathPrefix(uri, from, to) {
  if (uri === from || uri.indexOf(from + '/') === 0) {
    return to + uri.substring(from.length);
  }
  return null;
}

/**
 * Target for the old apex /admin and /auth URLs, or null. Segments match the
 * way the old app's router did: case-insensitively and percent-decoded.
 */
function appHostRedirect(uri, querystring) {
  var rest = stripSegment(uri, 'auth');
  if (rest !== null) {
    // Never forward an OAuth code or state to another host.
    return NOTEBOOK_ORIGIN + '/';
  }
  rest = stripSegment(uri, 'admin');
  if (rest === null) {
    return null;
  }
  var origin = ADMIN_ORIGIN;
  var notebookRest = stripSegment(rest, 'notebook');
  if (notebookRest !== null) {
    origin = NOTEBOOK_ORIGIN;
    rest = notebookRest;
  }
  return origin + (rest || '/') + serializeQueryString(querystring);
}

/** The rest of `uri` after a leading `/<name>` segment, or null. */
function stripSegment(uri, name) {
  if (uri.charAt(0) !== '/') {
    return null;
  }
  var slash = uri.indexOf('/', 1);
  var segment = slash === -1 ? uri.substring(1) : uri.substring(1, slash);
  var decoded;
  try {
    decoded = decodeURIComponent(segment).toLowerCase();
  } catch (e) {
    return null;
  }
  if (decoded !== name) {
    return null;
  }
  return slash === -1 ? '' : uri.substring(slash);
}

function isOptionBPage(page) {
  var pages =
    OPTION_B_PAGES_OVERRIDE !== null ? OPTION_B_PAGES_OVERRIDE : OPTION_B_PAGES;
  return pages.indexOf(page) !== -1;
}

function setOptionBPagesForTests(pages) {
  OPTION_B_PAGES_OVERRIDE = pages;
}

/** Lowercase letters, digits and hyphens. `__x__` is reserved for sentinels. */
function isValidSlug(slug) {
  if (!slug || slug.length > MAX_SLUG_LENGTH) {
    return false;
  }
  if (
    slug.length >= 4 &&
    slug.indexOf('__') === 0 &&
    slug.substring(slug.length - 2) === '__'
  ) {
    return false;
  }
  for (var i = 0; i < slug.length; i++) {
    var c = slug.charCodeAt(i);
    var ok = (c >= 48 && c <= 57) || (c >= 97 && c <= 122) || c === 45;
    if (!ok) {
      return false;
    }
  }
  return true;
}

async function isPublishedKey(key, syncedKey) {
  if (PUBLISHED_KEYS_OVERRIDE !== null) {
    return Object.prototype.hasOwnProperty.call(PUBLISHED_KEYS_OVERRIDE, key);
  }
  try {
    var kvsHandle = cf.kvs();
    // exists(key) first: one KVS read for a published page.
    var keyExists;
    try {
      keyExists = await kvsHandle.exists(key);
    } catch (e) {
      return true;
    }
    if (keyExists) {
      return true;
    }
    try {
      if (await kvsHandle.exists(syncedKey)) {
        return false;
      }
      return true;
    } catch (e) {
      return true;
    }
  } catch (e) {
    return true;
  }
}

/** Keys as stored in the KVS: `<post-slug>` and `projects/<slug>`. */
function setPublishedKeysForTests(keys) {
  PUBLISHED_KEYS_OVERRIDE = keys;
}

/** CloudFront may pass the path percent-encoded or already decoded. */
function isLegacyResumePdfUri(uri) {
  var candidate = uri;
  for (var i = 0; i < 2; i++) {
    if (candidate === LEGACY_RESUME_PDF) {
      return true;
    }
    try {
      var decoded = decodeURIComponent(candidate);
      if (decoded === candidate) {
        break;
      }
      candidate = decoded;
    } catch (e) {
      break;
    }
  }
  return candidate === LEGACY_RESUME_PDF;
}

function serializeQueryString(qs) {
  if (!qs) {
    return '';
  }
  var parts = [];
  for (var key in qs) {
    if (!Object.prototype.hasOwnProperty.call(qs, key)) {
      continue;
    }
    var item = qs[key];
    if (item.multiValue) {
      for (var i = 0; i < item.multiValue.length; i++) {
        parts.push(key + '=' + item.multiValue[i].value);
      }
    } else if (item.value !== undefined) {
      parts.push(key + '=' + item.value);
    } else {
      parts.push(key + '=');
    }
  }
  return parts.length ? '?' + parts.join('&') : '';
}
